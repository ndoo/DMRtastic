# DFU protocol constants
_VID = 0x0483
_PID = 0xDF11
_INTF = 0
_TIMEOUT = 5000  # ms
_BLOCK_SIZE = 1024

# DFU request codes (USB DFU 1.1 spec)
_DFU_DNLOAD   = 1
_DFU_GETSTATUS = 3
_DFU_CLRSTATUS = 4
_DFU_GETSTATE  = 5

# DFU states
_STATE_DFU_DNLOAD_IDLE = 5
_STATE_DFU_DNLOAD_BUSY = 4
_STATE_DFU_ERROR       = 10

_dev = None


def _open_device():
    import usb.core
    import usb.util
    global _dev
    _dev = usb.core.find(idVendor=_VID, idProduct=_PID)
    if _dev is None:
        raise RuntimeError(
            f'TYT DFU device not found (VID={_VID:#06x} PID={_PID:#06x}). '
            'Hold PTT+SK1 and power on the radio.')
    # Detach kernel driver if needed (Linux only; macOS raises USBError).
    try:
        if _dev.is_kernel_driver_active(0):
            _dev.detach_kernel_driver(0)
    except usb.core.USBError:
        pass  # macOS: not needed, ignore
    _dev.set_configuration()


def _get_status():
    resp = _dev.ctrl_transfer(0xA1, _DFU_GETSTATUS, 0, _INTF, 6, _TIMEOUT)
    poll_ms = resp[1] | (resp[2] << 8) | (resp[3] << 16)
    return resp[4], poll_ms  # bState, bwPollTimeout in ms


def _wait_idle():
    for _ in range(100):
        state, _ = _get_status()
        if state == _STATE_DFU_DNLOAD_IDLE:
            return
        if state == _STATE_DFU_ERROR:
            _dev.ctrl_transfer(0x21, _DFU_CLRSTATUS, 0, _INTF, None, _TIMEOUT)
            raise RuntimeError('DFU device entered error state')
        time.sleep(0.01)
    raise RuntimeError('Timed out waiting for DFU idle state')


def _dnload(block_num, data):
    _dev.ctrl_transfer(0x21, _DFU_DNLOAD, block_num, _INTF, data, _TIMEOUT)
    _, poll_ms = _get_status()  # moves state machine; bootloader reports how long to wait
    if poll_ms > 0:
        time.sleep(poll_ms / 1000)
    _wait_idle()


def _send_unlock():
    """Send the two proprietary unlock commands required by the TYT bootloader.

    These commands must be sent before any erase or write or the bootloader
    silently discards all subsequent DFU data.
    """
    _dnload(0, bytes([0x91, 0x01]))
    _dnload(0, bytes([0x91, 0x31]))


def _set_address(address):
    """DfuSe set-address-pointer command (0x21 + 4-byte LE address)."""
    payload = struct.pack('<BI', 0x21, address)
    _dnload(0, payload)


def _page_erase(address):
    """DfuSe page-erase command (0x41 + 4-byte LE address)."""
    payload = struct.pack('<BI', 0x41, address)
    _dnload(0, payload)


_BAR_WIDTH = 40


def _write_progress(done: int, total: int) -> None:
    if done == 0:
        sys.stdout.write('[')
        sys.stdout.flush()
        return
    chars_now = _BAR_WIDTH * done // total
    chars_prev = _BAR_WIDTH * (done - _BLOCK_SIZE) // total
    sys.stdout.write('=' * (chars_now - chars_prev))
    if done >= total:
        sys.stdout.write('>]\n')
    sys.stdout.flush()


def encode(data: bytes) -> bytes:
    """XOR-encode raw binary for transmission to the TYT bootloader."""
    cipher = _CIPHER
    return bytes(b ^ cipher[i % 1024] for i, b in enumerate(data))


def _find_cdc_port():
    """Return the first CDC ACM port, or None."""
    import glob
    ports = sorted(glob.glob('/dev/ttyACM*') + glob.glob('/dev/cu.usbmodem*'))
    return ports[0] if ports else None


def _trigger_reboot_via_cdc(port):
    """Reboot the running firmware via the 1200 bps line-coding touch.

    The firmware calls NVIC_SystemReset() on DTR falling at 1200 bps.
    Call this only after the user has confirmed they are holding PTT+SK1,
    so the TYT bootloader enters DFU mode on the subsequent power-on.
    Source: src/usb.c usbd_event_handler; arduino/ArduinoCore-samd CDC.cpp.
    """
    try:
        import serial
    except ImportError:
        return False
    try:
        with serial.Serial(port, baudrate=1200, timeout=0.5):
            time.sleep(0.1)  # hold open so SET_LINE_CODING + DTR both land
        # port close deasserts DTR — firmware triggers NVIC_SystemReset()
        return True
    except Exception as e:
        print(f'CDC reboot failed ({e})')
        return False


def _wait_for_dfu(timeout=10):
    """Poll until the TYT DFU device enumerates (VID 0x0483, PID 0xDF11)."""
    import usb.core
    print('Waiting for DFU device...', end='', flush=True)
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if usb.core.find(idVendor=_VID, idProduct=_PID) is not None:
            print(' found.')
            return True
        time.sleep(0.25)
        print('.', end='', flush=True)
    print()
    return False


def flash(bin_path: str, no_cdc: bool = False) -> None:
    """Flash a raw .bin file to the TYT MD-UV390 application partition.

    If the firmware is running (CDC ACM port present), send the DFU trigger
    command first, then wait for the device to re-enumerate as a DFU device.
    If no_cdc is True, skip that step (device must already be in DFU mode).
    """
    with open(bin_path, 'rb') as f:
        raw = f.read()

    # Pad to block size boundary with 0xFF (erased flash value)
    remainder = len(raw) % _BLOCK_SIZE
    if remainder:
        raw += b'\xff' * (_BLOCK_SIZE - remainder)

    encoded = encode(raw)

    if not no_cdc:
        import usb.core
        if usb.core.find(idVendor=_VID, idProduct=_PID) is None:
            port = _find_cdc_port()
            if port:
                # Firmware is running. Ask user to hold buttons first, then
                # reboot via 1200 bps touch so the TYT bootloader sees PTT+SK1.
                input('Hold PTT+SK1, then press Enter to reboot the radio...')
                _trigger_reboot_via_cdc(port)
            else:
                # No firmware CDC port — prompt for manual DFU entry.
                input('Hold PTT+SK1 and power on the radio, then press Enter...')

            if not _wait_for_dfu(timeout=15):
                raise RuntimeError(
                    'DFU device did not enumerate. '
                    'Check USB cable and that PTT+SK1 were held at power-on.')
        else:
            print('DFU device already present.')

    _open_device()

    # Application partition: 0x0800C000 onwards.
    # Layout (from DFU alt=0 descriptor):
    #   1 × 16 KB sector  (sector 3)  — 0x0800C000
    #   1 × 64 KB sector  (sector 4)  — 0x08010000
    #   7 × 128 KB sectors (sectors 5-11) — 0x08020000 … 0x080E0000
    APP_BASE = 0x0800_C000
    SECTOR_ADDRS = (
        [0x0800_C000] +                       # 1 × 16 KB
        [0x0801_0000] +                       # 1 × 64 KB
        [0x0802_0000 + i * 0x2_0000 for i in range(7)]  # 7 × 128 KB
    )

    # Determine which sectors we actually need to erase
    end_addr = APP_BASE + len(encoded)
    SECTOR_SIZES = (
        [0x4000] +     # 16 KB
        [0x1_0000] +   # 64 KB
        [0x2_0000] * 7  # 128 KB each
    )
    sectors_needed = []
    for addr, size in zip(SECTOR_ADDRS, SECTOR_SIZES):
        if addr < end_addr:
            sectors_needed.append(addr)

    _send_unlock()

    print(f'Erasing {len(sectors_needed)} sector(s)...')
    for addr in sectors_needed:
        print(f'  erase 0x{addr:08X}')
        _page_erase(addr)

    total = len(encoded)
    print(f'Writing {total >> 10} kB ({total // _BLOCK_SIZE} blocks)...')
    _set_address(APP_BASE)

    block_num = 2  # DfuSe data blocks start at 2 (0 and 1 are command blocks)
    offset = 0
    _write_progress(0, total)
    while offset < total:
        chunk = encoded[offset:offset + _BLOCK_SIZE]
        _dnload(block_num, chunk)
        offset += _BLOCK_SIZE
        block_num += 1
        _write_progress(offset, total)

    print('Write complete. Resetting device...')

    # Jump to application: set address to bootloader entry, zero-length DNLOAD
    _set_address(0x0800_0000)
    _dev.ctrl_transfer(0x21, _DFU_DNLOAD, 0, _INTF, None, _TIMEOUT)
    try:
        _get_status()
    except Exception:
        pass  # device resets immediately; USB error is expected

    import usb.util
    usb.util.dispose_resources(_dev)


def main():
    ap = argparse.ArgumentParser(
        description='Flash a raw .bin to the TYT MD-UV390 via its proprietary DFU protocol.')
    ap.add_argument('bin', help='Path to the .bin file to flash')
    ap.add_argument('--no-cdc', action='store_true',
                    help='Skip CDC ACM DFU trigger; device must already be in DFU mode '
                         '(PTT+SK1 at power-on)')
    ap.add_argument('--dry-run', action='store_true',
                    help='Encode the binary and print info without touching the device')
    args = ap.parse_args()

    if args.dry_run:
        with open(args.bin, 'rb') as f:
            raw = f.read()
        enc = encode(raw)
        print(f'Input:   {len(raw)} bytes')
        print(f'Encoded: {len(enc)} bytes')
        print(f'First 8 raw bytes: {raw[:8].hex()}')
        print(f'First 8 enc bytes: {enc[:8].hex()}')
        return

    flash(args.bin, no_cdc=args.no_cdc)
    print('Flash complete.')
    sys.exit(0)


if __name__ == '__main__':
    main()
